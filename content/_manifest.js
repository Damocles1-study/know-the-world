/* 卷册总表 —— 新增一卷：在这里加一行，并在 index.html 加一个 <script> */
window.W = (function(){
  const vols = [], index = {};
  return {
    vols, index,
    vol(m){ m.items = []; vols.push(m); index[m.id] = m; return m; },
    add(id, ...items){ const v = index[id]; items.forEach(i=>{ i.v = id; v.items.push(i); }); },
    get(id){ for(const v of vols) for(const i of v.items) if(i.id===id) return i; }
  };
})();

